// 目的：声明并对外开放帖龄过滤器，剔除超过最大时长的旧帖。
// 影响：保证推荐内容的新鲜度，降低旧内容曝光占比。
pub mod age_filter;
// 目的：声明并对外开放社交关系过滤器，剔除被查看用户拉黑/静音的作者内容。
// 影响：尊重用户拉黑静音设置，避免展示用户明确不想要的内容。
pub mod author_socialgraph_filter;
// 目的：声明并对外开放核心数据完整性过滤器，剔除缺少作者或正文的候选。
// 影响：保证进入后续阶段的内容具备基本的可展示字段，减少脏数据。
pub mod core_data_hydration_filter;
// 目的：声明并对外开放会话去重过滤器，同一会话树仅保留分数最高的候选。
// 影响：避免同一对话的多条回复同时占据推荐位，提升结果多样性。
pub mod dedup_conversation_filter;
// 目的：声明并对外开放重复帖过滤器，去除同一 tweet_id 的重复候选。
// 影响：防止同一条帖子在结果中重复出现。
pub mod drop_duplicates_filter;

// 目的：声明并对外开放订阅资格过滤器，剔除用户未订阅的付费作者内容。
// 影响：保证仅展示用户有权限查看的付费订阅内容。
pub mod ineligible_subscription_filter;
// 目的：声明并对外开放静音关键词过滤器，剔除命中静音关键词的帖子。
// 影响：尊重用户关键词静音设置，过滤不希望看到的内容。
pub mod muted_keyword_filter;
// 目的：声明并对外开放已见帖子过滤器，基于客户端上报的 seen_ids 与布隆过滤器剔除已看过的帖子。
// 影响：避免重复推荐用户已看过的内容，提升新鲜感。
pub mod previously_seen_posts_filter;
// 目的：声明并对外开放已服务帖子过滤器，仅在下拉刷新(bottom request)时剔除近期已输出的帖子。
// 影响：减少同一批次内重复输出，控制加载更多的内容重叠。
pub mod previously_served_posts_filter;
// 目的：声明并对外开放转发去重过滤器，同一原始帖只保留首次出现（原帖或转发）。
// 影响：避免原帖与其多条转发同时出现在结果中，提高多样性。
pub mod retweet_deduplication_filter;
// 目的：声明并对外开放本人帖子过滤器，剔除作者就是当前用户自己的帖子。
// 影响：首页不推荐用户自己发布的帖子，聚焦他人内容。
pub mod self_tweet_filter;
// 目的：声明并对外开放可见性(安全)过滤器，依据 VF 返回的过滤原因决定候选是否保留。
// 影响：符合安全策略的内容被剔除，保护用户体验与合规。
pub mod vf_filter;
